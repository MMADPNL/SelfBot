# =========================================================
# Validation
# =========================================================

def validate_config():
    """
    بررسی تنظیمات ضروری ربات
    """

    errors = []

    if not BOT_TOKEN:
        errors.append(
            "BOT_TOKEN تنظیم نشده است."
        )

    if OWNER_ID <= 0:
        errors.append(
            "OWNER_ID تنظیم نشده است."
        )

    if errors:
        raise RuntimeError(
            "\n".join(errors)
        )

    return True
